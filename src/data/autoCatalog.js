const collator = new Intl.Collator('uk', {
  sensitivity: 'base',
  numeric: true,
})

function normalizeAutoBrand(brand) {
  return String(brand || '').trim()
}

function buildOptions(values, emptyLabel = '') {
  const options = [...values].sort(collator.compare).map((value) => ({
    value,
    label: value,
  }))

  return emptyLabel ? [{ value: '', label: emptyLabel }, ...options] : options
}

function getAllAutoModels() {
  return buildOptions([...new Set(Object.values(AUTO_CATALOG).flat())]).map((item) => item.value)
}

export function getAutoBrandOptions({ includeAll = false } = {}) {
  const brandOptions = buildOptions(Object.keys(AUTO_CATALOG), 'Усі марки')
  return includeAll ? brandOptions : brandOptions.filter((item) => item.value)
}

export function getAutoModelOptions(brand, { includeAll = false } = {}) {
  const normalizedBrand = normalizeAutoBrand(brand)
  if (!normalizedBrand) {
    return includeAll ? [{ value: '', label: 'Усі моделі' }] : []
  }

  const brandModels = AUTO_CATALOG[normalizedBrand]
  const models = brandModels && brandModels.length ? brandModels : getAllAutoModels()
  const modelOptions = buildOptions(models, 'Усі моделі')

  return includeAll ? modelOptions : modelOptions.filter((item) => item.value)
}

export function isKnownAutoBrand(brand) {
  return Boolean(AUTO_CATALOG[normalizeAutoBrand(brand)])
}
